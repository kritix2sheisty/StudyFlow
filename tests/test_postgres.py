"""
Postgres is optional. These tests check the SQL translation with no
database, and, when STUDYFLOW_TEST_POSTGRES=1 and DATABASE_URL point
at a real server, that the same storage calls work there.
"""

import os
import uuid
from datetime import date

import pytest

import storage
from models import Assignment, Priority, TimeSlot, Weekday


def test_database_url_accepts_herokus_postgres_scheme(monkeypatch):
    monkeypatch.setenv("DATABASE_URL", "postgres://user:pw@host:5432/db")
    assert storage.database_url() == "postgresql://user:pw@host:5432/db?sslmode=require"
    monkeypatch.setenv("DATABASE_URL", "postgresql://user:pw@localhost:5432/db")
    assert storage.database_url() == "postgresql://user:pw@localhost:5432/db"
    monkeypatch.setenv("DATABASE_URL", "")
    assert storage.database_url() == ""


def test_set_db_path_stays_on_sqlite_even_with_database_url(monkeypatch, tmp_path):
    monkeypatch.setenv("DATABASE_URL", "postgres://user:pw@host/db")
    storage.set_db_path(tmp_path / "pinned.db")
    storage.init_db()
    assert (tmp_path / "pinned.db").is_file()


def test_adapt_sql_turns_sqlite_into_postgres():
    create = "id INTEGER PRIMARY KEY AUTOINCREMENT,"
    assert "AUTOINCREMENT" not in storage.adapt_sql(create)
    assert "GENERATED BY DEFAULT AS IDENTITY" in storage.adapt_sql(create)

    ignore = "INSERT OR IGNORE INTO session_completions (user_id) VALUES (?)"
    adapted = storage.adapt_sql(ignore)
    assert adapted.startswith("INSERT INTO session_completions")
    assert "OR IGNORE" not in adapted
    assert adapted.endswith("ON CONFLICT DO NOTHING")
    assert "%s" in adapted and "?" not in adapted

    upsert = "ON CONFLICT(user_id) DO UPDATE SET fingerprint = excluded.fingerprint"
    assert storage.adapt_sql("VALUES (?, ?)\n" + upsert).count("%s") == 2


@pytest.mark.skipif(os.environ.get("STUDYFLOW_TEST_POSTGRES") != "1", reason="no Postgres in this run")
def test_storage_round_trip_on_postgres():
    pinned = storage._sqlite_only
    storage._sqlite_only = False
    assert storage.database_url()
    try:
        _round_trip()
    finally:
        storage._sqlite_only = pinned


def _round_trip():
    storage.init_db()
    email = f"pg-{uuid.uuid4().hex}@example.com"
    uid = storage.add_user(email)
    with pytest.raises(storage.sqlite3.IntegrityError):
        storage.add_user(email)

    assignment_id = storage.add_assignment(uid, Assignment(
        name="Problem set", subject="Math", due_date=date(2026, 11, 1),
        estimated_hours=2.5, priority=Priority.HIGH,
    ))
    assert storage.list_assignments(uid)[0].id == assignment_id
    assert storage.list_assignments(uid)[0].estimated_hours == 2.5

    slot_id = storage.add_time_slot(uid, TimeSlot(weekday=Weekday.MONDAY, start_hour=16, end_hour=18))
    assert storage.list_time_slots(uid)[0].id == slot_id

    assert storage.add_session_completion(uid, assignment_id, "2026-11-01", 960, 1020) is True
    assert storage.add_session_completion(uid, assignment_id, "2026-11-01", 960, 1020) is False
    assert storage.done_minutes_by_assignment(uid) == {assignment_id: 60}

    storage.save_plan(uid, "fp", "2026-11-01T00:00:00", "{}")
    storage.save_plan(uid, "fp2", "2026-11-02T00:00:00", '{"n":1}')
    assert storage.get_plan(uid).fingerprint == "fp2"
    storage.init_db()
